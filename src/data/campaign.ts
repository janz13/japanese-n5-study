export function getCampaignStage(stageId: string): { stage: CampaignStage; saga: CampaignSaga } | null {
  for (const saga of CAMPAIGN_SAGAS) {
    const stage = saga.stages.find((s) => s.id === stageId);
    if (stage) return { stage, saga };
  }
  return null;
}

